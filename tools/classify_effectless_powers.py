"""Write docs/EFFECTLESS-POWERS.md: every player-pickable power whose record
carries no effect rows, sorted into a class by server/effectless.py.

Read-only over the shipped data; changes no game math. It exists because the
owner's review of PR #25 made "damaging powers the model does not read" a
rating-release blocker: no M4 offense grade ships for a build that picks one.

Usage: python tools/classify_effectless_powers.py [--check]
       (--check fails when the doc is stale vs the data)
"""
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))

import effectless  # noqa: E402

OUT = ROOT / "docs" / "EFFECTLESS-POWERS.md"
ORDER = ("unread_twins_damage", "damaging_unread", "unread_twins", "effect_unread",
         "modeled_elsewhere", "mechanic", "auto_granted")
MEANING = {
    "unread_twins_damage": "DAMAGE in records we already ship (the power's redirect twins); nothing reads them",
    "damaging_unread": "the game's help names damage (or the power takes Damage enhancement); no record of ours carries it",
    "unread_twins": "non-damage effects in records we already ship; nothing reads them",
    "effect_unread": "the game's help names an effect our record does not carry",
    "modeled_elsewhere": "Mastermind upgrade: priced by its re-cast time (encounter_value)",
    "mechanic": "accepts no enhancement: a mode switch that carries nothing by design",
    "auto_granted": "level_available < 1: the game issues it, never a pick",
}


def load():
    def read(name):
        return json.loads((ROOT / "data" / name).read_text(encoding="utf-8"))
    return read("powers.json"), read("powersets.json"), read("power_help.json")


def render(rows):
    counts = Counter(r["class"] for r in rows)
    out = ["# Effect-less player powers",
           "",
           "Generated by `tools/classify_effectless_powers.py` from `server/effectless.py`. "
           "Do not edit by hand; regenerate. Read-only: nothing here changes game math.",
           "",
           "**Rating-release blocker (owner review of PR #25):** no M4 offense grade ships for a "
           "build that picks a power in the first two classes. `/build/evaluate` reports them "
           "per build (`unsupported.powers`, `damaging: true`, `confidence.offense_complete`).",
           "",
           f"{len(rows)} pickable records carry no effect rows:",
           "",
           "| class | count | meaning |",
           "|---|---|---|"]
    out += [f"| {c} | {counts.get(c, 0)} | {MEANING[c]} |" for c in ORDER]
    for cls in ORDER:
        members = [r for r in rows if r["class"] == cls]
        if not members:
            continue
        out += ["", f"## {cls} ({len(members)})", "", "| power | display name | evidence |",
                "|---|---|---|"]
        out += [f"| `{r['power']}` | {r.get('display_name') or ''} | "
                f"{r['evidence'].replace('|', '/')} |" for r in members]
    return "\n".join(out) + "\n"


def main():
    rows = effectless.catalogue(*load())
    text = render(rows)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/EFFECTLESS-POWERS.md is stale: run tools/classify_effectless_powers.py")
            return 1
        print(f"docs/EFFECTLESS-POWERS.md current ({len(rows)} records)")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} records, "
          + ", ".join(f"{c} {n}" for c, n in Counter(r['class'] for r in rows).most_common()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
